export function getMailComposeEmojiCatalog(): string[] {
  const seen = new Set<string>();
  const all: string[] = [];
  for (const category of MAIL_COMPOSE_EMOJI_CATEGORIES) {
    for (const emoji of category.emoji) {
      if (seen.has(emoji)) continue;
      seen.add(emoji);
      all.push(emoji);
    }
  }
  return all;
}

export function filterMailComposeEmoji(
  query: string,
  categoryId: MailComposeEmojiCategoryId = "smileys",
): string[] {
  const normalized = query.trim().toLowerCase();
  const source =
    MAIL_COMPOSE_EMOJI_CATEGORIES.find((category) => category.id === categoryId)
      ?.emoji ?? getMailComposeEmojiCatalog();
  if (!normalized) {
    return [...source];
  }
  return [...source].filter((emoji) => emoji.includes(normalized));
}

